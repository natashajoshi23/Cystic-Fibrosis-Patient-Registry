-- 6. PATIENTS (mock data created)
CREATE TABLE patients (
    patient_id     INT PRIMARY KEY AUTO_INCREMENT,
    first_name     VARCHAR(50),
    last_name      VARCHAR(50),
    sex            ENUM('M','F'),
    birth_date     DATE,
    diagnosis_date DATE,
    ethnicity      VARCHAR(50),
    country        VARCHAR(50));

-- 7. PATIENT_MUTATIONS (patient genotype)
CREATE TABLE patient_mutations (
    patient_mutation_id INT PRIMARY KEY AUTO_INCREMENT,
    patient_id          INT NOT NULL,
    mutation_id         INT NOT NULL,
    allele              ENUM('Allele 1','Allele 2') NOT NULL,
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (mutation_id) REFERENCES mutations(mutation_id)); 

-- 8. PATIENT_SYMPTOMS
CREATE TABLE patient_symptoms (
    patient_symptom_id INT PRIMARY KEY AUTO_INCREMENT,
    patient_id         INT NOT NULL,
    symptom_id         INT NOT NULL,
    onset_age_years    DECIMAL(4,1),
    severity           ENUM('Mild','Moderate','Severe'),
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (symptom_id) REFERENCES symptoms(symptom_id));

-- 9. TREATMENTS  (drugs tried by each patient)
CREATE TABLE treatments (
    treatment_id INT PRIMARY KEY AUTO_INCREMENT,
    patient_id   INT NOT NULL,
    drug_id      INT NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE,
    dosage       VARCHAR(50),
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (drug_id) REFERENCES drugs(drug_id));

-- 10. OUTCOMES  (clinical outcome per treatment)
CREATE TABLE outcomes (
    outcome_id        INT PRIMARY KEY AUTO_INCREMENT,
    treatment_id      INT NOT NULL,
    fev1_change_pct   DECIMAL(5,2),
    sweat_chloride_change DECIMAL(5,1),
    outcome_status    ENUM('Improved','No Change','Worsened','Discontinued - Side Effects'),
    notes             VARCHAR(255),
    FOREIGN KEY (treatment_id) REFERENCES treatments(treatment_id));

-- 11. TRIAL_PARTICIPATION
CREATE TABLE trial_participation (
    participation_id INT PRIMARY KEY AUTO_INCREMENT,
    patient_id       INT NOT NULL,
    trial_id         INT NOT NULL,
    enrollment_date  DATE,
    completion_status VARCHAR(30),
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    FOREIGN KEY (trial_id) REFERENCES clinical_trials(trial_id));

